# Mendeley Data record 10.17632/x8psbz3f6x.2. The whole-record archive is served
# via the Mendeley public-api zip endpoint, which 302-redirects to a freshly
# signed S3 URL; the static cache-bucket URL is no longer publicly GETtable.
# Per-subject folders (``S1`` .. ``S60``) are not individually addressable.
MILIMBEEG_URL = "https://data.mendeley.com/public-api/zip/x8psbz3f6x/download/2"

# 16 dry electrodes (OpenBCI Cyton+Daisy) in channel order 1..16, read off the
# authors' 10-10 placement figure ``16_OpenBCI_electrodes_10_10system.png``.
CHANNELS = [
    "FC5",  # 1
    "F3",  # 2
    "Fz",  # 3
    "F4",  # 4
    "FC6",  # 5
    "FC1",  # 6
    "FC2",  # 7
    "Cz",  # 8
    "T7",  # 9
    "CP5",  # 10
    "C3",  # 11
    "CP1",  # 12
    "CP2",  # 13
    "C4",  # 14
    "CP6",  # 15
    "T8",  # 16
]

SFREQ = 125.0

# Task label -> event code, mirroring the authors' encoding (1..8).
EVENTS = {
    "beo": 1,  # baseline eyes open
    "clh": 2,  # closing left hand
    "crh": 3,  # closing right hand
    "dlf": 4,  # dorsal flexion left foot
    "plf": 5,  # plantar flexion left foot
    "drf": 6,  # dorsal flexion right foot
    "prf": 7,  # plantar flexion right foot
    "rest": 8,  # rest between tasks
}


class MILimbEEG(BaseDataset):
    """Motor and motor-imagery limb EEG dataset (MILimbEEG) [1]_ [2]_.

    **Dataset description**

    MILimbEEG contains over 8,680 four-second EEG recordings from 60 healthy
    volunteers, acquired with an OpenBCI Cyton+Daisy amplifier (16 dry
    electrodes, monopolar montage referenced to a neutral ear) sampled at
    125 Hz. Signals were hardware band-pass filtered (5-50 Hz) with a 60 Hz
    notch. The 16 electrodes cover the fronto-central and sensorimotor cortex
    following the international 10-10 system.

    Each subject completed one to four experiment repetitions. Within a
    repetition, participants first performed the movements physically (motor
    execution, ``M``) and then imagined them (motor imagery, ``I``). This
    loader exposes the **motor-imagery** trials only, consistent with
    ``paradigm='imagery'``; each experiment repetition is returned as a
    separate session.

    Eight task labels are encoded (matching the authors' scheme):

    - 1 ``beo``  : baseline eyes open (once per repetition)
    - 2 ``clh``  : closing left hand
    - 3 ``crh``  : closing right hand
    - 4 ``dlf``  : dorsal flexion of the left foot
    - 5 ``plf``  : plantar flexion of the left foot
    - 6 ``drf``  : dorsal flexion of the right foot
    - 7 ``prf``  : plantar flexion of the right foot
    - 8 ``rest`` : rest between tasks

    The six limb-movement classes are each recorded five times per repetition;
    ``beo`` occurs once and ``rest`` many times. Individual per-trial CSV files
    (electrode columns x time-sample rows, in microvolts) are concatenated per
    session into a single continuous recording, and a stimulus annotation marks
    the onset of every 4 s trial.

    .. warning::

        The per-subject data are hosted on Mendeley Data in folders
        (``S1`` .. ``S60``) that are not individually addressable through the
        public download API, and the whole-record archive is only served
        through a session-signed URL generated by the Mendeley web app. The
        download link used here (the Mendeley zip cache) may therefore require
        manual retrieval. The file layout, channel order, sampling rate and
        event encoding were all verified against the record's documentation.

    References
    ----------

    .. [1] Asanza, V., Montoya, D., Lorente-Leyva, L. L., Peluffo-Ordonez,
       D. H., & Gonzalez, K. (2023). MILimbEEG: A dataset of EEG signals
       related to upper and lower limb execution of motor and motor imagery
       tasks. Data in Brief, 50, 109540.
       DOI: https://doi.org/10.1016/j.dib.2023.109540

    .. [2] Asanza, V., Montoya, D., Lorente-Leyva, L. L., Peluffo-Ordonez,
       D. H., & Gonzalez, K. (2022). MILimbEEG. Mendeley Data, V2.
       DOI: https://doi.org/10.17632/x8psbz3f6x.2

    Notes
    -----

    .. versionadded:: 1.2.1

    """

    METADATA = DatasetMetadata(
        acquisition=AcquisitionMetadata(
            sampling_rate=125.0,
            n_channels=16,
            channel_types={"eeg": 16},
            montage="10-10",
            hardware="OpenBCI Cyton+Daisy",
            sensor_type="dry",
            electrode_type="dry",
            reference="neutral ear (monopolar)",
            ground=None,
            sensors=CHANNELS,
            line_freq=60.0,
            auxiliary_channels=AuxiliaryChannelsMetadata(has_eog=False, has_emg=False),
        ),
        participants=ParticipantMetadata(
            n_subjects=60, health_status="healthy", species="homo sapiens"
        ),
        experiment=ExperimentMetadata(
            paradigm="imagery",
            n_classes=8,
            class_labels=list(EVENTS.keys()),
            trial_duration=4.0,
            study_design=(
                "Upper- and lower-limb motor execution and motor imagery. Per "
                "repetition, participants first performed then imagined hand "
                "closing (left/right) and foot flexion (dorsal/plantar, "
                "left/right), with a baseline-eyes-open and rest periods."
            ),
            feedback_type="none",
            stimulus_type="visual",
            stimulus_modalities=["visual"],
            synchronicity="cue-based",
            mode="offline",
            events=EVENTS,
        ),
        documentation=DocumentationMetadata(
            doi="10.1016/j.dib.2023.109540",
            description=(
                "Over 8,680 four-second EEG recordings from 60 volunteers "
                "performing and imagining upper- and lower-limb movements, "
                "recorded with a 16-channel OpenBCI Cyton+Daisy at 125 Hz."
            ),
            investigators=[
                "Victor Asanza",
                "Daniel Montoya",
                "Leandro L. Lorente-Leyva",
                "Diego H. Peluffo-Ordonez",
                "Kleber Gonzalez",
            ],
            institution="Escuela Superior Politecnica del Litoral (ESPOL)",
            country="EC",
            data_url="https://doi.org/10.17632/x8psbz3f6x.2",
            publication_year=2023,
            keywords=[
                "motor imagery",
                "motor execution",
                "EEG",
                "brain-computer interface",
                "upper limb",
                "lower limb",
                "OpenBCI",
            ],
            license="CC-BY-4.0",
            repository="Mendeley Data",
        ),
        sessions_per_subject=1,
        runs_per_session=1,
        tags=Tags(pathology=["healthy"], modality=["Motor"], type=["Motor Imagery"]),
        preprocessing=PreprocessingMetadata(
            data_state="raw",
            preprocessing_applied=True,
            preprocessing_steps=["hardware band-pass 5-50 Hz", "60 Hz notch"],
            highpass_hz=5.0,
            lowpass_hz=50.0,
            bandpass=[5.0, 50.0],
        ),
        paradigm_specific=ParadigmSpecificMetadata(
            detected_paradigm="imagery",
            imagery_tasks=list(EVENTS.keys()),
            imagery_duration_s=4.0,
        ),
        data_structure=DataStructureMetadata(
            trials_context=(
                "Per repetition and per activity type (execution/imagery): 1 "
                "baseline-eyes-open, 5 trials each of 6 limb movements, and 31 "
                "rest trials (62 files); only the imagery files are loaded here."
            )
        ),
        file_format="CSV",
        contributing_labs=["ESPOL", "Hospital General Luis Vernaza"],
    )

    def __init__(self):
        super().__init__(
            subjects=list(range(1, 60 + 1)),
            sessions_per_subject=1,
            events=EVENTS,
            code="MILimbEEG",
            interval=[0.0, 4.0],
            paradigm="imagery",
            doi="10.1016/j.dib.2023.109540",
        )

    def data_path(
        self, subject, path=None, force_update=False, update_path=None, verbose=None
    ):
        if subject not in self.subject_list:
            raise ValueError("Invalid subject number")

        path_zip = Path(
            dl.data_dl(MILIMBEEG_URL, self.code, path=path, force_update=force_update)
        )
        extract_dir = path_zip.parent / "MILimbEEG"
        if not extract_dir.is_dir():
            with z.ZipFile(path_zip, "r") as zip_ref:
                zip_ref.extractall(extract_dir)

        # Subject folders may sit at the archive root or under a single wrapper
        # directory; resolve both layouts.
        candidates = [
            extract_dir / f"S{subject}",
            *(Path(p) for p in glob.glob(str(extract_dir / "*" / f"S{subject}"))),
        ]
        subject_dir = next((c for c in candidates if c.is_dir()), candidates[0])
        return [str(subject_dir)]

    def _read_trial(self, csv_file):
        """Read one per-trial CSV as a (n_channels, n_times) array in volts."""
        # Files hold a leading sample-index column followed by the 16 electrode
        # columns, x time-sample rows, in microvolts (17 columns total; see the
        # Data in Brief paper). Some exports omit a header row; detect and
        # normalise to 16 EEG columns.
        frame = pd.read_csv(csv_file, header=None)
        if frame.iloc[0].map(lambda v: isinstance(v, str)).any():
            frame = pd.read_csv(csv_file)
        data = frame.to_numpy(dtype=float)
        if data.shape[1] != len(CHANNELS) and data.shape[0] == len(CHANNELS):
            data = data.T
        # Skip column 0 (sample index), keep the 16 electrode columns 1..16,
        # convert microvolts -> volts, and orient as (channels, times).
        return data[:, 1 : len(CHANNELS) + 1].T * 1e-6

    @staticmethod
    def _label_of(csv_file):
        """Extract the task label code from a ``S<n>R<r>I<z>_<rep>.csv`` name."""
        stem = Path(csv_file).stem
        marker = stem.split("I", 1)[1] if "I" in stem else ""
        digits = ""
        for ch in marker:
            if ch.isdigit():
                digits += ch
            else:
                break
        return int(digits) if digits else None

    def _get_single_subject_data(self, subject):
        subject_dir = Path(self.data_path(subject)[0])
        sub = f"S{subject}"

        # Motor-imagery files only: S<n>R<r>I<z>_<rep>.csv (excludes execution "M").
        imagery_files = sorted(glob.glob(str(subject_dir / f"{sub}R*I*_*.csv")))

        # Group by repetition R<r> -> one session per repetition.
        sessions_files = {}
        for f in imagery_files:
            name = Path(f).stem
            rep = name.split("R", 1)[1].split("I", 1)[0]
            sessions_files.setdefault(rep, []).append(f)

        code_to_name = {v: k for k, v in EVENTS.items()}
        info = mne.create_info(
            ch_names=CHANNELS + ["STI 014"],
            sfreq=SFREQ,
            ch_types=["eeg"] * len(CHANNELS) + ["stim"],
        )

        # Trials are separate fixed-length recordings; concatenate them with a
        # short zero gap so the default [0, 4] s epoch never crosses into the
        # neighbouring (different-class) trial.
        pad = int(round(0.2 * SFREQ))

        sessions = {}
        for sess_idx, rep in enumerate(sorted(sessions_files)):
            segments = []
            events = []
            cursor = 0
            gap = np.zeros((len(CHANNELS) + 1, pad))
            for f in sorted(sessions_files[rep]):
                code = self._label_of(f)
                if code is None or code not in code_to_name:
                    continue
                trial = self._read_trial(f)
                stim = np.zeros((1, trial.shape[1]))
                stim[0, 0] = code
                segments.append(np.vstack([trial, stim]))
                segments.append(gap)
                events.append([cursor, 0, code])
                cursor += trial.shape[1] + pad

            if not segments:
                continue

            raw = mne.io.RawArray(np.concatenate(segments, axis=1), info, verbose=False)
            raw.set_montage("standard_1020", on_missing="ignore", verbose=False)
            annotations = mne.annotations_from_events(
                np.asarray(events), sfreq=SFREQ, event_desc=code_to_name, verbose=False
            )
            raw.set_annotations(annotations)
            sessions[str(sess_idx)] = {"0": raw}

        return sessions
